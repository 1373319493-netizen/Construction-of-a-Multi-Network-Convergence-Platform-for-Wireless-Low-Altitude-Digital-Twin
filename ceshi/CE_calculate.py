import csv
import matplotlib.pyplot as plt

# 从CSV文件读取数据
filename = '/home/estar/cosin-env/test/b1m1_house_data.csv'  # 替换为你的CSV文件名
with open(filename, 'r') as file:
    reader = csv.reader(file)
    data = list(reader)

# 提取第2列从第9行开始的数据
column_index = 1  # 第2列的索引为1
start_row = 2500     # 第9行的索引为8
end_row = 5000
values = [float(row[column_index]) for row in data[start_row:]]

# 生成x轴数据
x = list(range(len(values)))

# 绘制图形
plt.figure(figsize=(8, 6))
plt.plot(x, values, marker='o', linestyle='-', color='blue')
plt.xlabel('Index')
plt.ylabel('Value')
plt.title('Data from CSV')
plt.grid(True)
plt.tight_layout()
plt.show()



